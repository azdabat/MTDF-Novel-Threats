def capture_of_test(test_file):
    """test_<capture>.yml -> <capture>"""
    base = os.path.basename(test_file)
    return base[len("test_"):-len(".yml")] if base.startswith("test_") else None


def load_yaml(path):
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def dump_yaml(path, data, header=None):
    with open(path, "w", encoding="utf-8") as fh:
        if header:
            fh.write(header.rstrip() + "\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=110)


def threat_dirs():
    return sorted(d for d in glob.glob(os.path.join(THREATS, "*"))
                  if os.path.isdir(d) and not os.path.basename(d).startswith("_"))


def detection_dirs(threat_dir):
    return sorted(os.path.dirname(p) for p in glob.glob(os.path.join(threat_dir, "detections", "*", "detection.yml")))


def captures(threat_dir):
    """{capture_id: (json_path, metadata)} for every telemetry/<id>.json with its <id>.yml."""
    out = {}
    for j in sorted(glob.glob(os.path.join(threat_dir, "telemetry", "*.json"))):
        cid = os.path.splitext(os.path.basename(j))[0]
        meta_path = os.path.splitext(j)[0] + ".yml"
        out[cid] = (j, load_yaml(meta_path) if os.path.exists(meta_path) else None)
    return out


def rule_file(det_dir):
    rules = sorted(glob.glob(os.path.join(det_dir, "*.kql")))
    return rules[0] if rules else None


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def materialize_tests(det_dir, capture_id, capture_path):
    """Build fixtures_<capture>/ and test_<capture>.yml for every test in detection.yml that names this capture."""
    meta = load_yaml(os.path.join(det_dir, "detection.yml"))
    made = []
    for t in meta.get("tests") or []:
        if t.get("capture") != capture_id:
            continue
        # Convert EVERY event (process creates enrich the network/file/registry rows with the acting
        # process's command line, parent and hashes), then keep only the tables this rule reads.
        events = m2m.load_events(capture_path)
        tables, _ = mde_mapping.convert_events(events)
        rule_text = open(rule_file(det_dir), encoding="utf-8").read()
        tables = {k: v for k, v in tables.items() if re.search(rf"\b{k}\b", rule_text)}
        fix = os.path.join(det_dir, f"fixtures_{capture_id}")
        if os.path.isdir(fix):
            shutil.rmtree(fix)
        rows = m2m.write_tables(tables, fix, quiet=True)
        test = {
            "name": f"{meta.get('title', os.path.basename(det_dir))} - {capture_id}",
            "rule": os.path.basename(rule_file(det_dir)),
            "fixture": f"fixtures_{capture_id}",
            "technique": ", ".join(meta.get("techniques") or []),
            "source": f"Lab capture {capture_id}",
            "catches": t.get("catches", ""),
            "maturity": t.get("maturity", "experimental"),
            "expect": t.get("expect") or {"must_fire": True},
        }
        if t.get("known_issue"):
            test["known_issue"] = t["known_issue"]
        dump_yaml(os.path.join(det_dir, f"test_{capture_id}.yml"), test,
                  header="# Generated by tools/add_capture.py from detection.yml - edit the tests: block there, not here.")
        made.append((os.path.basename(det_dir), rows))
    return made


def write_rule(src_path, det_dir):
    """Copy a production rule in as its lab build (widened ago() windows, each change marked // LAB:)."""
    raw = open(src_path, "rb").read().decode("utf-8-sig", errors="replace").replace("\r\n", "\n")
    text, notes = lab_build.lab_build(raw)
    dest = os.path.join(det_dir, os.path.basename(src_path))
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write(text)
    return dest, notes
