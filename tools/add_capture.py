#!/usr/bin/env python3
"""
add_capture.py - register a lab capture with a threat and build every test that uses it.

    python tools/add_capture.py --threat nodejs-runtime-abuse --capture node_capture.json \
        --id node_lab_2026_11 --title "Node.js lab emulation: loader, child processes, blockchain-RPC polling" \
        --emulation emulation/mtdf_node_lab.ps1

  1. copies the capture to threats/<threat>/telemetry/<id>.json (the raw Sysmon record, kept for
     forensics and hunting - it is the evidence the tests are built on);
  2. writes telemetry/<id>.yml: what produced it, when, on which host, event counts, SHA-256;
  3. for every detection whose detection.yml lists this capture under tests:, rebuilds
     fixtures_<id>/ (Defender-shaped) and test_<id>.yml.
Re-run it any time; it is idempotent.
"""
import argparse
import collections
import datetime
import os
import shutil
import sys

import threatkit as tk


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--threat", required=True)
    ap.add_argument("--capture", required=True, help="Export-SysmonWindow.ps1 JSON (or an OTRF dataset)")
    ap.add_argument("--id", required=True, help="lowercase_with_underscores, e.g. node_lab_2026_11")
    ap.add_argument("--title", required=True)
    ap.add_argument("--emulation", default="", help="path inside the threat folder of the script that produced it")
    ap.add_argument("--notes", default="")
    args = ap.parse_args()

    tdir = os.path.join(tk.THREATS, args.threat)
    if not os.path.isfile(os.path.join(tdir, "threat.yml")):
        sys.exit(f"no threat at threats/{args.threat}")
    os.makedirs(os.path.join(tdir, "telemetry"), exist_ok=True)
    dest = os.path.join(tdir, "telemetry", f"{args.id}.json")
    if os.path.abspath(args.capture) != os.path.abspath(dest):
        shutil.copyfile(args.capture, dest)

    events = tk.m2m.load_events(dest)
    if not events:
        sys.exit("no Sysmon events found in that capture - check the export")
    eids = collections.Counter(e["EventId"] for e in events)
    times = sorted(str(e.get("TimeCreated") or "") for e in events if e.get("TimeCreated"))
    hosts = sorted({str(e.get("Computer")) for e in events if e.get("Computer")})
    tk.dump_yaml(os.path.join(tdir, "telemetry", f"{args.id}.yml"), {
        "id": args.id, "title": args.title, "author": "Ala Dabat",
        "registered": datetime.date.today().isoformat(),
        "emulation": args.emulation, "hosts": hosts,
        "window_utc": {"start": times[0] if times else "", "end": times[-1] if times else ""},
        "events": sum(eids.values()),
        "sysmon_event_ids": {int(k): v for k, v in sorted(eids.items())},
        "sha256": tk.sha256(dest), "notes": args.notes,
    }, header="# Telemetry dataset metadata (OTRF-style) - generated by tools/add_capture.py")
    print(f"telemetry/{args.id}.json  {sum(eids.values())} events  {dict(sorted(eids.items()))}  hosts={hosts}")

    built = 0
    for ddir in tk.detection_dirs(tdir):
        for det, rows in tk.materialize_tests(ddir, args.id, dest):
            print(f"  {det:<40} test_{args.id}.yml  ({rows} fixture rows)")
            built += 1
    print(f"\n{built} test(s) built. Next: lab.ps1 (or python tools/run_tests.py -k {args.threat})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
